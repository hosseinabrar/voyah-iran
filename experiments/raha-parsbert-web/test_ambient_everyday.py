BOUNDARIES = ['نور صفحه رو کم کن', 'چراغ جلو رو روشن کن', 'دمای کابین رو زیاد کن',
              'چراغای داخل رو خاموش نکن', 'کابین رو روشن تر نکن', 'نور خونه رو کم کن']

def predict(text):
    request = urllib.request.Request('https://127.0.0.1:18766/api/intent',
        json.dumps({'text': text}).encode(), {'Content-Type': 'application/json'})
    with urllib.request.urlopen(request, context=ssl._create_unverified_context()) as response:
        return json.load(response)

class AmbientEverydayTest(unittest.TestCase):
    @unittest.skipUnless(__name__ == "__main__" or os.getenv("RAHA_LIVE_TEST"), "requires local trainer")
    def test_live(self):
        for action, slots, phrases in CASES:
            for text in phrases.strip().splitlines():
                with self.subTest(text=text):
                    r = predict(text)
                    self.assertEqual((r['accepted'], round(100*r['prediction']['score']), r['prediction']['label'], r['slots']),
                                     (True, 100, action, slots))
        for text in BOUNDARIES:
            with self.subTest(text=text):
                r = predict(text)
                self.assertFalse(r['accepted'] and round(100*r['prediction']['score']) == 100 and 'AMBIENT_LIGHT' in r['prediction']['label'])

if __name__ == '__main__':
    unittest.main()
