"""Generate content-revisioned offline app inventory; never include user data."""
from pathlib import Path
import hashlib,json
web=Path(__file__).resolve().parents[1]/'client/vi-remote'
files=sorted([p for p in web.iterdir() if p.is_file() and p.suffix in ('.js','.css','.html','.webmanifest') and p.name not in ('sw.js','precache.js')]+[p for folder in ('assets','vendor') for p in (web/folder).rglob('*') if p.is_file() and not p.name.startswith('.')])
entries={p.relative_to(web).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
version=hashlib.sha256(json.dumps(entries,sort_keys=True).encode()).hexdigest()[:20]
(web/'precache.js').write_text('// Generated by remote/tools/prepare-web-cache.py\nself.VI_ASSETS='+json.dumps(entries,sort_keys=True,separators=(',',':'))+';\nself.VI_CACHE="vi-remote-static-'+version+'";\n')
print('Offline inventory:',len(entries),'files')
