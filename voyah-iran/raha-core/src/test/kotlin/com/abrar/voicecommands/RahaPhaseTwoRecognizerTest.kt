    @Test fun combinedFragranceSlots() {
        val names = mapOf(
            2 to listOf("گل", "صد تومنی", "صد تومانی", "پیونی", "نازبو"),
            3 to listOf("مه", "مه آبی", "مه نمناک", "مه نمدار", "نمناک", "نمدار")
        )
        var count = 0
        for ((channel, aliases) in names) for(name in aliases)
            for(noun in listOf("رایحه", "خوشبوکننده", "عطر", "عطر پاش"))
                for((duration, minutes) in listOf("نیم ساعت" to 30, "یک ساعت" to 60, "شصت دقیقه" to 60, "نامحدود" to 0)) {
                    val phrase = "$noun $name رو با شدت متوسط برای $duration فعال کن"
                    val result = parser.recognize(phrase)
                    assertTrue("$phrase -> $result", result is Recognition.Matched)
                    val command = (result as Recognition.Matched).command
                    assertEquals(phrase, "CONFIGURE_FRAGRANCE", command.action)
                    assertEquals(phrase, mapOf("channel" to channel, "intensity" to "medium", "durationMinutes" to minutes, "enabled" to true), command.parameters)
                    count++
                }
        val plain = (parser.recognize("رایحه رو فعال کن") as Recognition.Matched).command
        assertEquals(mapOf("enabled" to true), plain.parameters)
        val named = (parser.recognize("رایحه مه رو فعال کن") as Recognition.Matched).command
        assertEquals(mapOf("enabled" to true, "channel" to 3), named.parameters)
        val timed = (parser.recognize("رایحه مه رو برای یک ساعت فعال کن") as Recognition.Matched).command
        assertEquals(mapOf("enabled" to true, "channel" to 3, "durationMinutes" to 60), timed.parameters)
        println("Combined fragrance: $count examples passed")
    }

