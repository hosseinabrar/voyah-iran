import assert from 'node:assert/strict';
import fs from 'node:fs';
const root=new URL('./app/src/main/assets/trainer/',import.meta.url);
const elements=new Map(['mic','level','text'].map(id=>[id,{style:{},classList:{add(){},remove(){}},disabled:false}]));
globalThis.window={};globalThis.document={getElementById:id=>elements.get(id)};
const calls=[];globalThis.AndroidTrainer={request:(...args)=>calls.push(args)};
const source=fs.readFileSync(new URL('web/native.js',root),'utf8');
const {request,microphone}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const p=request('session');window.nativeReply(calls.at(-1)[0],{name:'حسین'},null);assert.equal((await p).name,'حسین');
const rejected=request('feedback');window.nativeReply(calls.at(-1)[0],null,'خطا');await assert.rejects(rejected,/خطا/);
let cleared=0,result=null,message='';
const click=microphone({message:x=>message=x,display:x=>result=x,listening:()=>cleared++});
const start=click();assert.equal(calls.at(-1)[1],'listen');window.nativeReply(calls.at(-1)[0],{},null);await start;
window.nativeSpeech({type:'start'});assert.equal(cleared,1);assert.equal(elements.get('text').value,'');
window.nativeSpeech({type:'partial',text:'کولر روشن'});assert.equal(elements.get('text').value,'کولر روشن');
window.nativeSpeech({type:'level',level:42});assert.equal(elements.get('level').style.width,'42%');
window.nativeSpeech({type:'decoding'});assert.equal(elements.get('mic').disabled,true);
window.nativeSpeech({type:'result',result:{prediction:{score:1}}});assert.equal(result.prediction.score,1);assert.equal(elements.get('mic').disabled,false);
window.nativeSpeech({type:'start'});const cancel=click();assert.equal(calls.at(-1)[1],'cancel');window.nativeReply(calls.at(-1)[0],{},null);await cancel;
window.nativeSpeech({type:'cancel'});assert.equal(elements.get('level').style.width,'0');
window.nativeSpeech({type:'error',message:'خطا'});assert.equal(message,'خطا');
const html=fs.readFileSync(new URL('index.html',root),'utf8');
assert.match(html,/<textarea[^>]*readonly/);assert.doesNotMatch(html,/id="parse"/);assert.match(html,/id="share"/);
const app=fs.readFileSync(new URL('web/app.js',root),'utf8');
const displaySource=app.split('\n').find(line=>line.startsWith('function display('));
const resultClasses=new Set();
for(const id of ['result','feedback','action','parameters','score','personal','correction'])elements.set(id,{classList:{toggle:(name,enabled)=>enabled?resultClasses.add(name):resultClasses.delete(name)}});
const display=new Function('$','describeParameters',`let current; ${displaySource}; return display;`)(id=>elements.get(id),()=> '');
display({text:'سلام',prediction:{label:'UNKNOWN',score:1,title:'نامفهوم'},slots:{}});
assert.equal(resultClasses.has('unknown'),true);assert.equal(resultClasses.has('good'),false);
display({text:'فرمان',prediction:{label:'STOP_CHARGING',score:.9,title:'توقف شارژ'},slots:{}});
assert.equal(resultClasses.has('unknown'),false);assert.equal(resultClasses.has('good'),false);
display({text:'فرمان',prediction:{label:'STOP_CHARGING',score:1,title:'توقف شارژ'},slots:{}});
assert.equal(resultClasses.has('good'),true);
console.log('Native bridge, microphone lifecycle, result colors, readonly input and share control: passed');
